"""Which boards are live and where each one's KiCad project lives.

Active boards are generated, routed, checked and exported. Archived boards (the four-slot modular node,
2026-11-21 checkpoint, git tag `modular-checkpoint-2026-11`) are frozen copies under
hardware/archive/modular-2026-11: never regenerated by default, never checked in CI. Their lessons are in
that folder's README.
"""

from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
KICAD = ROOT / "hardware" / "kicad"
ARCHIVE = ROOT / "hardware" / "archive" / "modular-2026-11"

ACTIVE = ["TL-SN-002", "TL-DBG-001"]
ARCHIVED = ["TL-SN-001", "TL-MOD-001", "TL-MOD-002", "TL-MOD-003", "TL-MOD-004", "TL-TEST-001"]


def kicad_dir(name: str) -> pathlib.Path:
    """Project folder of `name`, active or archived."""
    return (ARCHIVE / "kicad" if name in ARCHIVED else KICAD) / name
