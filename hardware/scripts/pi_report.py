"""Power-integrity and thermal estimate for TL-SN-001 with kisi, written to hardware/results/pi.md.

    python3 hardware/scripts/pi_config.py   # regenerate the board's kisi.json first
    python3 hardware/scripts/pi_report.py   # needs Node >= 18 and kisi.mjs (KISI_MJS, default below)

kisi (github.com/riehlies/kisi, GPL-3.0) runs as an external program: download the pinned release once,
    curl -fsSL --create-dirs -o ~/.cache/talos-tools/kisi-bin/kisi.mjs \\
        https://github.com/riehlies/kisi/releases/download/v0.3.3/kisi.mjs
and check it against KISI_SHA256 below. Local and on demand, not in CI yet.
"""

from __future__ import annotations

import hashlib
import json
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
BOARD = ROOT / "hardware" / "kicad" / "TL-SN-001" / "TL-SN-001.kicad_pcb"
OUT = ROOT / "hardware" / "results" / "pi.md"
KISI = pathlib.Path(os.environ.get("KISI_MJS", "~/.cache/talos-tools/kisi-bin/kisi.mjs")).expanduser()
KISI_VERSION = "v0.3.3"
KISI_SHA256 = "951e5c82d2564be290c2050c345c088697dd9d1a167adf06dc80e8c9abc40cd1"


def kisi(*args: str) -> dict:
    p = subprocess.run(["node", str(KISI), *args], capture_output=True, text=True, check=True)
    return json.loads(p.stdout)


def main() -> int:
    if not KISI.exists():
        raise SystemExit(f"kisi.mjs not found at {KISI}: see this script's docstring")
    digest = hashlib.sha256(KISI.read_bytes()).hexdigest()
    if digest != KISI_SHA256:
        raise SystemExit(f"{KISI} is not kisi {KISI_VERSION} (sha256 {digest})")
    board = str(BOARD)
    power = kisi("power", board)
    lines = ["# TL-SN-001 power integrity and thermal estimate (generated)", "",
             f"Generated by `hardware/scripts/pi_report.py` with kisi {KISI_VERSION} from the routed board and "
             "`TL-SN-001.kisi.json` (`pi_config.py`). **USB worst case**: charging at 300 mA, radio transmitting, "
             "slots at the firmware's 800 mW admission budget (4 x 55 mA). Estimates, not measurements.", "",
             "## DC IR drop per rail", "",
             "| Rail | Load (A) | Max drop (mV) | Max current density (A/mm²) |", "|---|---:|---:|---:|"]
    for r in sorted(power["rails"], key=lambda r: -(r.get("max_drop_mv") or 0)):
        if r.get("max_drop_mv") is None:
            continue
        lines.append(f"| {r['rail'].lstrip('/')} | {r['load_a']:.3f} | {r['max_drop_mv']:.1f} | {r['max_j_a_mm2']:.0f} |")
    lines += ["", "Warnings: " + ("; ".join(power.get("warnings", [])) or "none"), ""]
    lines += ["## Thermal (steady state, still air, both sides)", "",
              "| Ambient (°C) | Board max (°C) | Hottest part | Tj (°C) | Next |", "|---:|---:|---|---:|---|"]
    for amb in ("25", "50"):
        t = kisi("thermal", board, "--ambient", amb)
        parts = sorted(t["parts"], key=lambda p: -p["tj_c"])
        nxt = ", ".join(f"{p['ref']} {p['tj_c']:.0f}" for p in parts[1:4])
        lines.append(f"| {amb} | {t['summary']['t_board_max_c']:.1f} | {parts[0]['ref']} {parts[0]['part']} "
                     f"({parts[0]['heat_w']:.2f} W) | {parts[0]['tj_c']:.1f} | {nxt} |")
    lines += ["", "The radio's 0.5 W is a burst, so the steady-state figures overstate it. Most θ values are kisi "
              "package defaults (estimate) until `PI_THERMAL` rows carry datasheet values.", ""]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
