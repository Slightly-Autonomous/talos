"""Magnet field at the TL-MOD-001 TMAG5273 versus gap, for candidate door magnets (magpylib).

    python3 -m pip install magpylib   # once (CI does this)
    python3 hardware/scripts/magnet_sim.py          # writes hardware/results/magnet.md
    python3 hardware/scripts/magnet_sim.py --check  # exit 1 if the committed file is out of date

The firmware calls the door closed above 3 mT and open below 1.5 mT on the strongest axis
(modules.h Tmag5273ContactDriver), on the TMAG5273A1's +/-40 mT range. No magnet is specified yet: this
sizes one. Analytic fields in free space (magpylib's closed-form solutions): no steel door, frame or
enclosure, which can bend or shunt the field by tens of percent. The gap is measured from the magnet face to
the sensor die. Remanence values are the low end of each grade's standard range.
"""

from __future__ import annotations

import pathlib
import sys

import magpylib as magpy
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "hardware" / "results" / "magnet.md"

CLOSE_MT, OPEN_MT, RANGE_MT = 3.0, 1.5, 40.0  # modules.h kCloseUt, kOpenUt, kLsbPerMt range
BR = {"N35": 1.17, "N52": 1.42}  # T, low end of grade (IEC 60404-8-1 style grade tables)
MAGNETS = [  # (label, shape, dimensions in mm, grade)
    ("disc 6 x 3 mm", "cyl", (6, 3), "N35"),
    ("disc 10 x 3 mm", "cyl", (10, 3), "N35"),
    ("disc 10 x 3 mm", "cyl", (10, 3), "N52"),
    ("block 20 x 5 x 3 mm (typical door contact)", "cuboid", (20, 5, 3), "N35"),
]
OFFSETS_MM = (0.0, 5.0)  # lateral misalignment of magnet and sensor (door sag, mounting)


def magnet(shape: str, dims, br: float):
    m = 1e-3
    if shape == "cyl":
        d, h = dims
        return magpy.magnet.Cylinder(polarization=(0, 0, br), dimension=(d * m, h * m), position=(0, 0, -h * m / 2))
    a, b, c = dims
    return magpy.magnet.Cuboid(polarization=(0, 0, br), dimension=(a * m, b * m, c * m), position=(0, 0, -c * m / 2))


def strongest_axis_mt(src, gap_mm: float, offset_mm: float) -> float:
    b = src.getB((offset_mm * 1e-3, 0, gap_mm * 1e-3))
    return float(np.max(np.abs(b)) * 1e3)


def crossing(src, offset_mm: float, level_mt: float) -> float:
    """Largest gap (mm) at which the strongest axis still reads above level_mt."""
    gaps = np.arange(0.5, 80.0, 0.1)
    vals = np.array([strongest_axis_mt(src, g, offset_mm) for g in gaps])
    above = np.where(vals >= level_mt)[0]
    return float(gaps[above[-1]]) if len(above) else 0.0


def build() -> str:
    lines = ["# TL-MOD-001 magnet sizing (generated)", "",
             f"Generated by `hardware/scripts/magnet_sim.py` with magpylib {magpy.__version__}. Free-space analytic "
             "fields, no steel door or enclosure: **a model, not a measurement** (bench C1-06 replaces it).", "",
             f"Firmware thresholds: closed above {CLOSE_MT} mT, open below {OPEN_MT} mT, strongest axis; sensor range "
             f"±{RANGE_MT} mT.", "",
             "| Magnet | Grade | Offset (mm) | Closes within (mm) | Opens beyond (mm) | Field at 2 mm (mT) | Saturates at 2 mm |",
             "|---|---|---:|---:|---:|---:|---|"]
    for label, shape, dims, grade in MAGNETS:
        src = magnet(shape, dims, BR[grade])
        for off in OFFSETS_MM:
            close = crossing(src, off, CLOSE_MT)
            opn = crossing(src, off, OPEN_MT)
            b2 = strongest_axis_mt(src, 2.0, off)
            lines.append(f"| {label} | {grade} | {off:.0f} | {close:.1f} | {opn:.1f} | {b2:.1f} | "
                         f"{'yes' if b2 > RANGE_MT else 'no'} |")
    lines += ["", "### Threshold options (strongest axis, aligned)", "",
              "| Magnet | Close / open (mT) | Closes within (mm) | Opens beyond (mm) |", "|---|---|---:|---:|"]
    for label, shape, dims, grade in (MAGNETS[0], MAGNETS[3]):
        src = magnet(shape, dims, BR[grade])
        for c, o in ((CLOSE_MT, OPEN_MT), (10.0, 5.0), (20.0, 10.0), (35.0, 20.0)):
            lines.append(f"| {label} {grade} | {c:g} / {o:g} | {crossing(src, 0.0, c):.1f} | {crossing(src, 0.0, o):.1f} |")
    lines += ["", "Reading: a door gap below *closes within* reads closed; above *opens beyond* reads open; between "
              "the two the last state holds (hysteresis). Saturation above 40 mT is harmless for a contact (the "
              "reading clips at full scale) but hides the offset check of bench C1-06.", ""]
    return "\n".join(lines)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date: run hardware/scripts/magnet_sim.py")
            return 1
        print("magnet: results current")
        return 0
    OUT.write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
