#!/usr/bin/env python3
"""TL-SN-002 power budget (ADR 0019): 2 x AA lithium primary cells (or USB) through a TPS2116 power mux and
the TPS63900 buck-boost, every sensor on board, lamps dark on battery.

Every constant is tagged SRC (datasheet) or EST (assumption a bench must replace). A model, not a measurement.

Usage: python3 hardware/scripts/power_budget_sn2.py [--out hardware/results/power-budget-sn2.md]
Exits non-zero if HWR-009 (deep-sleep battery current < 40 uA) or the end-of-life TX check fails.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from power_budget import (CHECKINS_PER_DAY, EVENTS_PER_DAY, LIGHT_SLEEP_UA, RADIO_TX_PEAK_MA,  # noqa: E402
                          REG_EFF_ACTIVE, REG_EFF_LIGHT, SLEEP_LIMIT_UA, V_RAIL, Load, radio_avg_ua_3v3)

# ---- 2 x AA Li-FeS2 (Energizer L91 class) ----------------------------------------------
CELL_MAH = 3000.0  # SRC Energizer L91 datasheet, 25 mA continuous to 0.9 V/cell (lower at high drain)
CELLS = 2
V_PAIR_NOM = 3.0  # EST plateau ~1.5 V/cell at light load
V_PAIR_FRESH = 3.6  # SRC L91 open circuit ~1.8 V/cell fresh
V_PAIR_END = 1.8  # 0.9 V/cell end of life = TPS63900 VIN minimum (SRC SLVSET3D 1.8 V)
SELF_DISCHARGE_PCT_YEAR = 1.0  # SRC L91 "20-year shelf life", ~1 %/year EST
COLD_CAPACITY = 0.7  # EST at -20 C under pulse load (L91 rated to -40 C)
PAIR_R_OHM = {"25 C": 0.30, "-20 C": 0.60, "-40 C": 1.00}  # EST pair internal resistance (two cells + holder)
VIN_MIN = 1.8  # SRC TPS63900 operating input minimum

SLEEP_LOADS = [
    Load("ESP32-H2 deep sleep (LP timer + LP mem on)", 7.0, "3v3", "SRC MINI-1 v1.6 Table 16"),
    Load("TPS63900 IQ", 0.075, "bat", "SRC SLVSET3D IQ 75 nA"),
    Load("TPS2116 on VIN2 (battery mode) IQ", 1.32, "bat", "SRC SLVSFG1A IQ 1.32 uA typ"),
    Load("TCA9535 standby (lamps off, PIR_PWR held high)", 0.9, "3v3", "SRC SCPS201F ICC standby typ"),
    Load("TMAG5273A2 wake-and-sleep, 100 ms (EST as on TL-MOD-001)", 1.2, "3v3", "EST SLYS045C W&S"),
    Load("SN74AUP1G04 ICC", 0.5, "3v3", "SRC SCES571K ICC 0.5 uA max"),
    Load("LIS2DW12 low-power wake-up mode", 1.0, "3v3", "EST datasheet claims < 1 uA"),
    Load("SHT40 idle", 0.08, "3v3", "SRC Sensirion SHT4x idle 80 nA"),
    Load("PIR223D-S0 (always powered)", 10.0, "3v3", "SRC LCSC/NEWOPTO listing 10 uA"),
    Load("Tamper loop shut (R99 1 MOhm)", 3.3, "3v3", "design 3.3 V / 1 MOhm"),
    Load("VBAT sense divider 2 x 4.7 MOhm", 3.0 / 9.4, "bat", "design at the 3.0 V plateau"),
    Load("USB-present divider (no VBUS: no current)", 0.0, "bat", "design"),
    Load("Lamps dark on battery; I2C idle; USER/BOOT idle", 0.0, "3v3", "design (firmware lamp policy)"),
]


def battery_ua(loads, v_bat: float, eff: float) -> float:
    return sum(l.ua if l.rail == "bat" else l.ua * V_RAIL / (v_bat * eff) for l in loads)


def life_years(i_ua: float, capacity_mah: float) -> float:
    sd_ua = capacity_mah * 1000.0 * SELF_DISCHARGE_PCT_YEAR / 100.0 / 8760.0  # uA-equivalent
    return capacity_mah * 1000.0 / (i_ua + sd_ua) / 8760.0


def tx_min_ocv(r_ohm: float, eff: float = REG_EFF_ACTIVE) -> float:
    """Lowest pair open-circuit voltage at which an 18 dBm TX burst (plus CPU and sensors) keeps the
    TPS63900 input at VIN_MIN: V_oc = V_in + I_in * R with I_in = P_out / (eff * V_in), at V_in = VIN_MIN."""
    p_out_w = V_RAIL * (RADIO_TX_PEAK_MA + 30.0 + 5.0) / 1000.0  # TX + CPU + sensors/expander EST
    i_in = p_out_w / (eff * VIN_MIN)
    return VIN_MIN + i_in * r_ohm


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="hardware/results/power-budget-sn2.md")
    args = ap.parse_args()

    sleep = battery_ua(SLEEP_LOADS, V_PAIR_NOM, REG_EFF_LIGHT)
    sleep_end = battery_ua(SLEEP_LOADS, V_PAIR_END + 0.4, REG_EFF_LIGHT)
    radio_bat = radio_avg_ua_3v3(CHECKINS_PER_DAY + EVENTS_PER_DAY) * V_RAIL / (V_PAIR_NOM * REG_EFF_ACTIVE)
    sed = battery_ua([Load("H2 light sleep", LIGHT_SLEEP_UA, "3v3", "")] + SLEEP_LOADS[1:], V_PAIR_NOM,
                     REG_EFF_LIGHT) + radio_bat
    deep = sleep + radio_bat
    out = ["# TL-SN-002 power budget (generated)", "",
           "Generated by `hardware/scripts/power_budget_sn2.py` (ADR 0019). 2 × AA Li-FeS2 primary cells or "
           "USB-C; TPS2116 mux; TPS63900 3.3 V. **A model, not a measurement**: EST rows need a bench.", "",
           "## 1. Deep-sleep current at the cells", "", "| Load | µA | Rail | Basis |", "|---|---:|---|---|"]
    for l in SLEEP_LOADS:
        out.append(f"| {l.name} | {l.ua:.2f} | {l.rail} | {l.tag} |")
    out += ["", f"- **Sleep current at {V_PAIR_NOM} V: {sleep:.1f} µA** (at {V_PAIR_END + 0.4:.1f} V, "
                f"late in life: {sleep_end:.1f} µA). Limit HWR-009: < {SLEEP_LIMIT_UA:.0f} µA.",
            f"- Radio reports ({CHECKINS_PER_DAY + EVENTS_PER_DAY}/day, same model as TL-SN-001): "
            f"{radio_bat:.1f} µA average at the cells.", "",
            "## 2. Battery life (one pair of L91, 3000 mAh)", "",
            "| Sleep design | Avg µA | Life 25 °C (years) | Life, cold capacity (years) |", "|---|---:|---:|---:|"]
    for name, i in (("Deep sleep between reports", deep), ("Thread SED in light sleep", sed)):
        out.append(f"| {name} | {i:.1f} | {life_years(i, CELL_MAH):.1f} | {life_years(i, CELL_MAH * COLD_CAPACITY):.1f} |")
    out += ["", "Which sleep design the Thread stack can use is unverified (HD-004/HD-018).", "",
            "## 3. End of life under an 18 dBm TX burst", "",
            f"The TPS63900 needs ≥ {VIN_MIN} V at its input during the burst. Lowest pair open-circuit voltage "
            "that still delivers it, by temperature (pair resistance EST):", "",
            "| Temperature | Pair R (Ω) | Min OCV (V) | Per cell (V) |", "|---|---:|---:|---:|"]
    worst = 0.0
    for t, r in PAIR_R_OHM.items():
        v = tx_min_ocv(r)
        worst = max(worst, v)
        out.append(f"| {t} | {r:.2f} | {v:.2f} | {v / CELLS:.2f} |")
    low_batt = round(worst + 0.1, 1)
    out += ["", f"- **Firmware low-battery threshold (provisional): {low_batt:.1f} V under load** "
                f"({low_batt / CELLS:.2f} V/cell). Below it the node reports low battery and caps TX power.",
            f"- USB-C (VBUS ≥ 3.7 V by the TPS2116 PR1 divider) takes over from the cells automatically.", ""]
    checks = [(f"HWR-009 deep-sleep current < {SLEEP_LIMIT_UA:.0f} µA", sleep < SLEEP_LIMIT_UA),
              ("End-of-life TX threshold stays below the L91 plateau (3.0 V)", worst < V_PAIR_NOM)]
    out += ["## 4. Checks", ""] + [f"- [{'x' if ok else ' '}] {n}" for n, ok in checks] + [""]
    pathlib.Path(args.out).write_text("\n".join(out))
    for n, ok in checks:
        print(("PASS " if ok else "FAIL ") + n)
    print(f"sleep {sleep:.1f} uA, deep-sleep design {deep:.1f} uA, SED {sed:.1f} uA -> {args.out}")
    return 0 if all(ok for _, ok in checks) else 1


if __name__ == "__main__":
    sys.exit(main())
