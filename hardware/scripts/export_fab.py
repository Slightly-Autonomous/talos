#!/usr/bin/env python3
"""Export a fabrication package for each routed board with kicad-cli.

    python3 hardware/scripts/export_fab.py [BOARD ...]

Writes hardware/fab/<board>/: Gerbers + Excellon drill (zipped), pick-and-place CSV, BOM CSV (from
hardware/results/bom), JLCPCB-format BOM/CPL plus a not-assembled list (jlc_sourcing.py), top/bottom
3D renders, FAB-NOTES.txt (the order options the design depends on), an IPC-D-356 netlist and a
test-pad map (D-05: every test pad with its net and position, for probing and fixtures). This is a *prototype* package for quoting and DFM
review only. Nothing is ordered (HW-0005): ordering needs explicit owner approval.
"""

from __future__ import annotations

import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jlc_sourcing  # noqa: E402
from check_kicad import BOARDS, KICAD, RESULTS, ROOT, kicad_cli  # noqa: E402

FAB = ROOT / "hardware" / "fab"
CARDS = ("TL-MOD-001", "TL-MOD-002", "TL-MOD-003", "TL-MOD-004", "TL-TEST-001")


def fab_notes(board: str) -> str:
    """Order options the layout relies on. They are not visible in the Gerbers, so they are written down."""
    lines = [f"{board} rev A fabrication notes (generated by hardware/scripts/export_fab.py)",
             "PROTOTYPE: not reviewed by an electrical engineer. Nothing here authorises an order (HW-0005).", ""]
    lines.append("- Board thickness 1.6 mm (cards and slot hosts: 1.57 mm nominal for the Samtec HSEC8 socket).")
    lines.append("- 4 layers, stack F.Cu / In1 GND / In2 3V3 / B.Cu." if board == "TL-SN-001"
                 else "- 2 layers.")
    lines.append("- Vias 0.65/0.3 mm, 0.5 mm minimum hole-to-hole. Vias in the thermal pads (ESP32 module "
                 "GND, U4, U5): order epoxy-filled and capped vias (JLCPCB 'via in pad / POFV'), or the "
                 "thermal-pad solder wicks away (HD-039).")
    lines.append("- JLCPCB order number: choose 'specify position'; the bottom silk carries the "
                 "JLCJLCJLCJLC placeholder (M-04).")
    if board in CARDS:
        lines.append("- Gold fingers: hard gold (30 uin) on the card-edge contacts, 30 deg bevel on the finger "
                     "edge. Finger copper stops 0.65 mm short of the edge so the bevel clears it (HD-040).")
        lines.append("- Panelise with rails or mouse bites on the three non-finger edges only; the finger edge "
                     "must stay free for bevelling (HD-040).")
    if board == "TL-SN-001":
        lines.append("- Slot sockets and USB-C overhang three edges: no V-score on those edges; panel with "
                     "tabs (HD-040).")
        lines.append("- Mounting holes H1-H4: unplated 2.7 mm (M2.5).")
    if board == "TL-SN-002":
        lines.append("- Mounting holes H1-H4: unplated 2.7 mm (M2.5). Two slots cut in from the right edge form the "
                     "SHT40 thermal tongue: route them as plated-free slots, 1.2 mm wide.")
        lines.append("- Through-hole parts placed by JLCPCB: BT1 (Keystone 2462 2xAA holder) and U10 (PIR223D-S0). "
                     "Every other part is single-sided SMT; U1 (ESP32-H2-MINI-1-H4S) comes from JLCPCB Global "
                     "Sourcing (HD-023).")
    if board == "TL-DBG-001":
        lines.append("- Mounting holes H1-H4: unplated 3.2 mm (M3). TP20/TP21 Keystone 5001 loops are "
                     "hand-fitted after assembly (HD-042).")
    return "\n".join(lines) + "\n"


def test_pad_map(ipc: pathlib.Path) -> str:
    """Test pads from the IPC-D-356 netlist: ref, net, x, y (mm, drill-file origin), side."""
    import re

    rows = ["ref,net,x_mm,y_mm,side"]
    for line in ipc.read_text(errors="replace").splitlines():
        if not line.startswith(("317", "327")):
            continue
        net, ref = line[3:17].strip(), line[20:26].strip()
        if not ref.startswith("TP"):
            continue
        m = re.search(r"X([+-]?\d+)Y([+-]?\d+)", line)
        if not m:
            continue
        side = "top" if "A01" in line else "bottom" if "A02" in line else "both"
        rows.append(f"{ref},{net.lstrip('/')},{int(m.group(1)) / 1000:.3f},{int(m.group(2)) / 1000:.3f},{side}")
    return "\n".join(rows) + "\n"


def run(cmd: list[str]) -> None:
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        raise SystemExit(f"failed: {' '.join(cmd)}\n{p.stdout}\n{p.stderr}")


def export(cli: str, board: str) -> list[str]:
    pcb = KICAD / board / f"{board}.kicad_pcb"
    out = FAB / board
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    with tempfile.TemporaryDirectory() as tmp:
        g = pathlib.Path(tmp) / "gerbers"
        g.mkdir()
        inner = "In1.Cu,In2.Cu," if board == "TL-SN-001" else ""
        layers = f"F.Cu,{inner}B.Cu,F.Paste,B.Paste,F.Silkscreen,B.Silkscreen,F.Mask,B.Mask,Edge.Cuts"
        run([cli, "pcb", "export", "gerbers", "--layers", layers, "--no-protel-ext", "--subtract-soldermask",
             "--use-drill-file-origin", "-o", str(g), str(pcb)])
        run([cli, "pcb", "export", "drill", "--format", "excellon", "--excellon-separate-th", "--drill-origin", "plot",
             "--generate-map", "--map-format", "gerberx2", "-o", str(g) + "/", str(pcb)])
        with zipfile.ZipFile(out / f"{board}-gerbers.zip", "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(g.iterdir()):
                info = zipfile.ZipInfo(f.name, date_time=(2026, 1, 1, 0, 0, 0))  # stable zip for clean diffs
                z.writestr(info, _strip_dates(f.read_text(errors="replace")))
    run([cli, "pcb", "export", "pos", "--format", "csv", "--units", "mm", "--side", "both", "--use-drill-file-origin",
         "--exclude-dnp", "-o", str(out / f"{board}-cpl.csv"), str(pcb)])
    shutil.copy(RESULTS / "bom" / f"{board}.csv", out / f"{board}-bom.csv")
    jlc_sourcing.export([board])  # JLCPCB-format BOM/CPL + not-assembled list
    (out / "FAB-NOTES.txt").write_text(fab_notes(board))
    ipc = out / f"{board}.ipc356"
    run([cli, "pcb", "export", "ipcd356", "-o", str(ipc), str(pcb)])
    ipc.write_text(_strip_dates(ipc.read_text(errors="replace")))
    (out / f"{board}-test-pads.csv").write_text(test_pad_map(ipc))
    for side in ("top", "bottom"):
        run([cli, "pcb", "render", "--side", side, "--width", "1200", "--height", "900", "--quality", "basic",
             "-o", str(out / f"{board}-{side}.png"), str(pcb)])
    if board == "TL-SN-002":
        # B-05: the assembled board for the housing CAD. B-06/B-04: the conformal-coat keep-out map and the
        # housing keep-outs (housing_marks.py) as PDFs with the outline, for the coating step and printing.
        run([cli, "pcb", "export", "step", "--subst-models", "--force",
             "-o", str(out / f"{board}.step"), str(pcb)])
        for layer, what in (("User.Eco2", "no-coat-map"), ("User.Eco1", "housing-keepouts")):
            run([cli, "pcb", "export", "pdf", "--layers", f"Edge.Cuts,F.Fab,{layer}", "--include-border-title",
                 "-o", str(out / f"{board}-{what}.pdf"), str(pcb)])
    return sorted(p.name for p in out.iterdir())


def _strip_dates(text: str) -> str:
    """Drop generator timestamps so regenerated Gerbers diff cleanly."""
    keep = []
    for line in text.splitlines():
        if "CreationDate" in line or line.startswith("; #@! TF.CreationDate") or line.startswith(";DRILL file {KiCad"):
            continue
        keep.append(line)
    return "\n".join(keep) + "\n"


def main() -> int:
    cli = kicad_cli()
    for b in sys.argv[1:] or BOARDS:
        print(f"{b}: {', '.join(export(cli, b))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
