// Writes a Frigate config for Talos cameras (ADR 0020) from the connector's
// camera map, so the map is the one place a camera is declared:
//   tsx src/gen-config.ts cameras.json > frigate/config.yml
// cameras.json: {"patio": {"deviceId": "cam_patio_video", "token": "...",
//   "rtspUrl": "rtsp://talos:{FRIGATE_RTSP_PASSWORD}@cam-patio.local:8554/cam"}}
// The RTSP password stays out of the file: Frigate substitutes
// {FRIGATE_*} environment variables itself. Tokens are not written.
//
// Recording: alerts and detections keep 5 s before and after (the bookmark
// pre-roll, VB-05) for 14 days; snapshots for 14 days. Detection runs on the
// main stream at 5 fps (VB-08 may add a 640x360 detect stream).
// Keys follow Frigate 0.17's config reference; check them on upgrade.
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import type { CameraMapping } from "./frigate.ts";

export interface GenOptions {
  detector?: "cpu" | "hailo8l";
  retainDays?: number;
  detectFps?: number;
  width?: number;
  height?: number;
  detectUrls?: Record<string, string>; // optional second stream per camera
}

const NAME = /^[a-z0-9_]{1,32}$/;

function q(s: string): string {
  return JSON.stringify(s); // a JSON string is a valid YAML double-quoted scalar
}

export function genConfig(cameras: Record<string, CameraMapping>, o: GenOptions = {}): string {
  const days = o.retainDays ?? 14;
  const fps = o.detectFps ?? 5;
  const lines: string[] = [
    "# Generated by connectors/frigate/src/gen-config.ts (ADR 0020). Do not edit by hand.",
    "mqtt:",
    "  enabled: false",
    "detectors:",
    o.detector === "hailo8l" ? "  hailo8l:\n    type: hailo8l\n    device: PCIe" : "  cpu1:\n    type: cpu",
    "objects:",
    "  track: [person, car, dog, cat]",
    "record:",
    "  enabled: true",
    "  alerts:",
    "    pre_capture: 5",
    "    post_capture: 5",
    "    retain:",
    `      days: ${days}`,
    "  detections:",
    "    pre_capture: 5",
    "    post_capture: 5",
    "    retain:",
    `      days: ${days}`,
    "snapshots:",
    "  enabled: true",
    "  retain:",
    `    default: ${days}`,
    "cameras:",
  ];
  const names = Object.keys(cameras).sort();
  if (names.length === 0) throw new Error("no cameras");
  for (const name of names) {
    if (!NAME.test(name)) throw new Error(`camera name ${name}: use 1-32 of [a-z0-9_]`);
    const url = cameras[name]!.rtspUrl;
    if (!url || !url.startsWith("rtsp://")) throw new Error(`camera ${name}: rtspUrl must be rtsp://`);
    if (/:[^:@/{}]+@/.test(url.replace(/\{FRIGATE_[A-Z0-9_]+\}/g, ""))) {
      throw new Error(`camera ${name}: put the password in {FRIGATE_RTSP_PASSWORD}, not the file`);
    }
    const detect = o.detectUrls?.[name];
    lines.push(`  ${name}:`, "    ffmpeg:", "      inputs:");
    if (detect) {
      lines.push(`        - path: ${q(url)}`, "          roles: [record]");
      lines.push(`        - path: ${q(detect)}`, "          roles: [detect]");
    } else {
      lines.push(`        - path: ${q(url)}`, "          roles: [detect, record]");
    }
    lines.push(
      "    detect:",
      "      enabled: true",
      `      width: ${detect ? 640 : (o.width ?? 1920)}`,
      `      height: ${detect ? 360 : (o.height ?? 1080)}`,
      `      fps: ${fps}`,
    );
  }
  return lines.join("\n") + "\n";
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const file = process.argv[2];
  if (!file) {
    console.error("usage: gen-config.ts cameras.json [--hailo8l]");
    process.exit(2);
  }
  const cams = JSON.parse(readFileSync(file, "utf8")) as Record<string, CameraMapping>;
  process.stdout.write(
    genConfig(cams, { detector: process.argv.includes("--hailo8l") ? "hailo8l" : "cpu" }),
  );
}
